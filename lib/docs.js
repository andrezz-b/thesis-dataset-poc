// Generated documentation: e2e blocks (example READMEs), root README.md and ATTRIBUTION.md.
import { readFile, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import { config } from '../config.js'
import { root } from './registry.js'
import { readBuilt } from './runner.js'
import { commonsFileName, commonsPageUrl, exists } from './commons.js'
import { entityUrl } from './wikidata.js'

const START = '<!-- e2e:start (generated by `node cli.js docs`) -->'
const END = '<!-- e2e:end -->'
const cell = s => String(s).replace(/\|/g, '\\|')

async function readE2e(ex) {
  const path = join(ex.dist, 'e2e.json')
  if (!(await exists(path))) throw new Error(`${ex.meta.id}: no dist/e2e.json, run "node cli.js e2e ${ex.meta.id}" first`)
  return JSON.parse(await readFile(path))
}

// `base` is the path of the example folder relative to the README being written ('' or 'examples/<id>/')
function renderE2e(ex, e2e, base) {
  const img = (p, h) => `<img src="${encodeURI(base + p)}" height="${h}">`
  const rank = e2e.hits.findIndex(h => h.qid === e2e.goldQid) + 1
  const verdict = rank
    ? `Expected entity **${e2e.goldQid}** is at rank **${rank}**.`
    : `Expected entity **${e2e.goldQid}** is **not** in the top ${e2e.k}.`
  return [
    `**Query image** (\`${e2e.queryImage}\`):`, '',
    img(e2e.queryImage, 200), '',
    `Top-${e2e.k} of ${e2e.indexed} indexed entities (embedder: \`${e2e.embedder}\`). ${verdict}`, '',
    '| # | Image | Entity | Score |', '|---|---|---|---|',
    ...e2e.hits.map((h, i) =>
      `| ${i + 1} | ${img(h.image, 100)} | ${h.qid === e2e.goldQid ? '✅ ' : ''}**${cell(h.label)}** ([${h.qid}](${entityUrl(h.qid)})) | ${h.score.toFixed(4)} |`),
  ].join('\n')
}

async function updateExampleReadme(ex, e2e) {
  const path = join(ex.dir, 'README.md')
  const text = await readFile(path, 'utf8')
  const a = text.indexOf('<!-- e2e:start'), b = text.indexOf(END)
  if (a < 0 || b < a) throw new Error(`${path} must contain the markers:\n${START}\n${END}`)
  await writeFile(path, `${text.slice(0, a)}${START}\n\n${renderE2e(ex, e2e, '')}\n\n${text.slice(b)}`)
}

function renderRootReadme(sections) {
  return `# Image QA over Wikidata – proof of concept

Each sample is an **image of an entity** plus a **question answered by walking the Wikidata graph**.
An image is first matched to an entity through a CLIP embedding index (Qdrant), then the question is answered
with a SPARQL query over Wikidata.

> This file is generated by \`node cli.js docs\`. Edit the example metadata / READMEs instead.

## Quick start

\`\`\`bash
mise run install
mise run all                       # starts Qdrant, build + index + e2e for every example, then regenerates docs
mise run examples                  # available examples
\`\`\`

Tasks (\`mise tasks\`): \`vector:up\`, \`build [example] [--refresh]\`, \`index [example]\`, \`e2e [example]\`,
\`query <example> <image> [--k N]\`, \`docs\`, \`all [example]\`; they wrap \`node cli.js\`.
Configuration is read from environment variables, set in the \`[env]\` section of [mise.toml](mise.toml).
Image authors and licences: [ATTRIBUTION.md](ATTRIBUTION.md).

## Examples

${sections.join('\n\n')}
`
}

function renderRootSection(ex, e2e) {
  const { meta } = ex
  const dir = relative(root, ex.dir)
  return `### ${meta.name}

${meta.description}

- **Question:** ${meta.question}
- **Gold entity:** [${meta.goldEntity}](${entityUrl(meta.goldEntity)})

<details><summary>Gold query</summary>

\`\`\`sparql
${meta.goldQuery.trim()}
\`\`\`

</details>

#### End-to-end result

${renderE2e(ex, e2e, `${dir}/`)}

➡️ Full write-up: [${dir}/README.md](${dir}/README.md)`
}

async function renderAttribution(examples) {
  const sections = []
  for (const ex of examples) {
    const { entities, queryImage } = await readBuilt(ex)
    const gold = entities.find(e => e.qid === queryImage.goldQid)
    const rows = [
      ...entities.map(e => ({ label: `${e.label} (${e.qid})`, imageUrl: e.imageUrl, a: e.attribution })),
      ...(queryImage.imageUrl ? [{ label: `${gold?.label ?? queryImage.goldQid} (query image)`, imageUrl: queryImage.imageUrl, a: queryImage.attribution }] : []),
    ].map(r => {
      const f = commonsFileName(r.imageUrl)
      return `| ${cell(r.label)} | [${cell(f)}](${commonsPageUrl(f)}) | ${cell(r.a?.author ?? 'unknown')} | ${cell(r.a?.license ?? 'unknown')} |`
    })
    sections.push(`## ${ex.meta.name}\n\n| Entity | Commons file | Author | Licence |\n|---|---|---|---|\n${rows.join('\n')}`)
  }
  return `# Image attribution

All images are from Wikimedia Commons (via Wikidata P18), downscaled to ${config.imageWidth}px width. Each keeps its own licence.
This file is generated by \`node cli.js docs\`.

${sections.join('\n\n')}
`
}

export async function docs(examples) {
  const e2es = []
  for (const ex of examples) e2es.push(await readE2e(ex))
  const attribution = await renderAttribution(examples)
  for (const [i, ex] of examples.entries()) await updateExampleReadme(ex, e2es[i])
  await writeFile(join(root, 'README.md'), renderRootReadme(examples.map((ex, i) => renderRootSection(ex, e2es[i]))))
  await writeFile(join(root, 'ATTRIBUTION.md'), attribution)
  console.log(`docs: README.md, ATTRIBUTION.md and ${examples.length} example README(s) updated`)
}
